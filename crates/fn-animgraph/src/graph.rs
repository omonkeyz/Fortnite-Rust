/// `Get Cardinal Direction From Angle` (EventGraph function): South when |angle| >= 135 - deadzone, North when |angle| <= 45 + deadzone,
/// else East / West by the sign of the angle (bytecode lines 7696-7901 of the ubergraph).
pub fn cardinal_from_angle(angle:f32,dead_zone:f32)->Cardinal{
    if angle.abs()>=135.-dead_zone{Cardinal::South}else if angle.abs()<=45.+dead_zone{Cardinal::North}else if angle>0.{Cardinal::East}else{Cardinal::West}
}
/// Authored direction of the four cardinal clips (degrees in LocalVelocityYawAngle space).
