/// A montage playing on a slot (UpperBody, FullBodyInPlace, ...): the slot blends the source pose toward the montage pose by `weight`.
/// `FAnimNode_LayeredBoneBlend::CurveBlendOption` as serialized on each 1.8 node (see LAYERED.md): how the blend pose's curves join the base's.
#[derive(Clone,Copy,Debug,PartialEq,Eq)]pub enum CurveBlend{
    /// `ECurveBlendOption::BlendByWeight` (exe enum value 2): base curve + blend curve x node weight (`FBlendedCurve::Accumulate`, valid flags OR-ed);
    /// skipped when the weight is <= 1e-5. Exe-verified, see CURVE_BLEND.md.
    BlendByWeight,
    /// `ECurveBlendOption::MaxWeight` (exe enum value 0, the default branch of BlendPosesPerBoneFilter): despite the name this is an OVERRIDE, not a max():
    /// every curve that is VALID in the blend pose replaces the base value (weight-independent once the weight is > 1e-5); curves absent from the blend
    /// pose keep the base value. Exe-verified, see CURVE_BLEND.md. (`NormalizeByWeight` = 1 exists in the exe but no 1.8 node uses it.)
    MaxWeight,
}
/// How a slot node applies a montage's sequence: UE `FAnimInstance::SlotEvaluatePose` cross-fades a full pose and accumulates an additive one
/// (`FAnimationRuntime::AccumulateAdditivePose`), chosen by the sequence's `AdditiveAnimType`.
#[derive(Clone,Copy,Debug,Default,PartialEq,Eq)]pub enum SlotBlend{#[default]Pose,LocalAdditive,MeshAdditive}
#[derive(Clone,Debug)]pub struct Montage{pub slot:&'static str,pub clip:String,pub time:f32,pub weight:f32,pub blend:SlotBlend}

/// Melee_Equip montage: UpperBody slot, blend-in 0.0667 s, blend-out 0.7 s (the montage is only 0.7718 s long, so the
/// blend-out starts 0.0718 s in, as UE starts it when the remaining time equals the blend-out time).
#[derive(Clone,Copy,Debug,Default)]pub struct Equip{pub time:f32,pub active:bool}
impl Equip{
    pub fn start(&mut self){self.time=0.;self.active=true;}
    pub fn step(&mut self,dt:f32){if self.active{self.time+=dt.max(0.);if self.time>=EQUIP_LENGTH{self.active=false;}}}
    pub fn weight(&self)->f32{
        if !self.active{return 0.;}
        let w_in=ease(EQUIP_BLEND_IN.ease,self.time/EQUIP_BLEND_IN.dur);
        let out_start=EQUIP_LENGTH-EQUIP_BLEND_OUT.dur;
        let w_out=if self.time>out_start{1.-ease(EQUIP_BLEND_OUT.ease,(self.time-out_start)/EQUIP_BLEND_OUT.dur)}else{1.};
        w_in.min(w_out)
    }
    /// Time inside Melee_WideGrip_Equip_CMM (the segment starts at AnimStartTime).
    pub fn clip_time(&self)->f32{(EQUIP_ANIM_START+self.time).min(EQUIP_ANIM_END)}
}

