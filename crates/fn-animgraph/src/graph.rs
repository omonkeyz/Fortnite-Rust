#[derive(Clone,Copy,Debug,PartialEq)]pub enum Ease{Linear,Hermite}
/// UE `EAlphaBlendOption`: HermiteCubic is the 3t^2-2t^3 ease, Linear is the identity.
pub fn ease(e:Ease,t:f32)->f32{let t=t.clamp(0.,1.);match e{Ease::Linear=>t,Ease::Hermite=>t*t*(3.-2.*t)}}
#[derive(Clone,Copy,Debug,PartialEq)]pub struct Tr{pub dur:f32,pub ease:Ease}
const fn tr(dur:f32,ease:Ease)->Tr{Tr{dur,ease}}
/// `FMath::FInterpTo`.
pub fn finterp_to(current:f32,target:f32,dt:f32,speed:f32)->f32{
    if speed<=0.{return target;}let dist=target-current;if dist*dist<1.0e-8{return target;}current+dist*(dt*speed).clamp(0.,1.)
}
/// `FMath::FInterpTo_Constant`.
pub fn finterp_constant(current:f32,target:f32,dt:f32,speed:f32)->f32{let d=target-current;if d*d<1.0e-8{return target;}current+(speed*dt).min(d.abs())*d.signum()}
/// `UKismetMathLibrary::NormalizeAxis` (-180, 180].
pub fn normalize_axis(a:f32)->f32{let mut r=a.rem_euclid(360.);if r>180.{r-=360.;}r}
pub fn map_range_clamped(v:f32,in_a:f32,in_b:f32,out_a:f32,out_b:f32)->f32{let t=if (in_b-in_a).abs()<1e-9{0.}else{((v-in_a)/(in_b-in_a)).clamp(0.,1.)};out_a+(out_b-out_a)*t}

