/// Runs a rule list: the first rule whose condition holds fires (the automatic rule fires when the state's remaining time <= its blend).
fn evaluate(rules:&[Rule],v:&Vars,remaining:Option<f32>)->Option<Rule>{
    for r in rules{let fire=if r.auto{remaining.map_or(false,|t|t<=r.tr.dur)}else{(r.rule)(v)};if fire{return Some(*r);}}None
}

