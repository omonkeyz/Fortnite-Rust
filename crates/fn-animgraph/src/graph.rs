// Generic cross-fading state machine (UE 4.16 AnimNode_StateMachine semantics: per-state weights, restart on entry)
// ------------------------------------------------------------------------------------------------------------------------------
#[derive(Clone,Debug)]pub struct Sm{pub cur:usize,pub w:Vec<f32>,pub t:Vec<f32>,start:Vec<f32>,fade_t:f32,dur:f32,ease:Ease,fading:bool,pub entered:Vec<bool>,pub prof:Profile}
impl Sm{
    pub fn new(n:usize,initial:usize)->Self{let mut w=vec![0.;n];w[initial]=1.;Self{cur:initial,start:w.clone(),w,t:vec![0.;n],fade_t:0.,dur:0.,ease:Ease::Linear,fading:false,entered:vec![false;n],prof:Profile::None}}
    /// Starts a transition to `to` (restarts the target's clock when it had no weight; marks it for per-state resets).
    pub fn go(&mut self,to:usize,t:Tr,prof:Profile){
        if to==self.cur{return;}
        for e in &mut self.entered{*e=false;}
        if self.w[to]<=1e-4{self.t[to]=0.;self.entered[to]=true;}
        self.start=self.w.clone();self.cur=to;self.fade_t=0.;self.dur=t.dur;self.ease=t.ease;self.fading=true;self.prof=prof;
        if t.dur<=1e-6{self.finish();}
    }
    fn finish(&mut self){for (i,w) in self.w.iter_mut().enumerate(){*w=if i==self.cur{1.}else{0.};}self.fading=false;}
    /// Advances every state with weight and updates the blend weights.
    pub fn tick(&mut self,dt:f32){
        for i in 0..self.w.len(){if self.w[i]>1e-4||i==self.cur{self.t[i]+=dt;}}
        if self.fading{
            self.fade_t+=dt;let a=if self.dur<=1e-6{1.}else{ease(self.ease,self.fade_t/self.dur)};
            for i in 0..self.w.len(){self.w[i]=if i==self.cur{self.start[i]+(1.-self.start[i])*a}else{self.start[i]*(1.-a)};}
            if self.fade_t>=self.dur{self.finish();}
        }
    }
    pub fn fading(&self)->bool{self.fading}
    /// True once after `i` was (re)entered from zero weight (the engine re-initialises that state's players); clears the flag.
    pub fn take_entered(&mut self,i:usize)->bool{std::mem::replace(&mut self.entered[i],false)}
}
/// One baked transition: target state, blend, rule and whether it is the automatic remaining-time rule.
/// Blend profile of a baked transition (skeleton BlendProfile): per-bone scale of the blend weight (`clamp(weight * scale)`), FastFeet moves the legs faster, SlowTorso the spine slower.
#[derive(Clone,Copy,Debug,PartialEq,Eq)]pub enum Profile{None,FastFeet,SlowTorso}
impl Profile{pub fn table(self)->Option<&'static [(&'static str,f32)]>{match self{Profile::None=>None,Profile::FastFeet=>Some(FAST_FEET),Profile::SlowTorso=>Some(SLOW_TORSO)}}}
#[derive(Clone,Copy)]pub struct Rule{pub to:usize,pub tr:Tr,pub auto:bool,pub rule:fn(&Vars)->bool,pub prof:Profile}
fn never(_:&Vars)->bool{false}

