    /// Effective weight of every clip leaf in the pose tree (Mix normalised; additive / layered children weighted by alpha / weight).
    fn leaf_weights(n:&Node,w:f32,out:&mut Vec<(String,f32)>){
        let mut add=|name:&str,w:f32|{if w>1e-4{match out.iter_mut().find(|(c,_)|c==name){Some(o)=>o.1+=w,None=>out.push((name.to_owned(),w))}}};
        match n{
            Node::Clip{name,..}=>add(name,w),
            Node::Mix(v)=>{let t:f32=v.iter().map(|(_,x)|*x).sum();if t>1e-6{for (c,x) in v{leaf_weights(c,w*x/t,out);}}}
            Node::MixProfile{from,to,w:t,..}=>{leaf_weights(from,w*(1.-t),out);leaf_weights(to,w*t,out);}
            Node::ApplyAdditive{base,add:a,alpha}|Node::ApplyMeshAdditive{base,add:a,alpha}=>{leaf_weights(base,w,out);leaf_weights(a,w*alpha,out);}
            Node::Layered{base,blend,weight,..}=>{leaf_weights(base,w*(1.-weight),out);leaf_weights(blend,w*weight,out);}
            Node::AimOffset{base,..}|Node::RotateRoot{base,..}|Node::TwoBoneIk{base,..}|Node::HandRetarget{base,..}|Node::CopyBone{base,..}|Node::ModifyBone{base,..}|Node::HeadTrack{base,..}=>leaf_weights(base,w,out),
            Node::Ref=>{}}
    }
