    #[derive(Debug,Clone)]enum Tok{Ident(String),Num(f32),LP,RP,Not,And,Or,Gt,Ge,Lt,Le,Eq}
    fn tokenize(s:&str)->Vec<Tok>{
        let b:Vec<char>=s.chars().collect();let mut i=0;let mut out=vec![];
        while i<b.len(){let c=b[i];
            match c{' '=>{i+=1;}'('=>{out.push(Tok::LP);i+=1;}')'=>{out.push(Tok::RP);i+=1;}'!'=>{out.push(Tok::Not);i+=1;}
                '&'=>{out.push(Tok::And);i+=2;}'|'=>{out.push(Tok::Or);i+=2;}
                '>'=>{if b.get(i+1)==Some(&'='){out.push(Tok::Ge);i+=2;}else{out.push(Tok::Gt);i+=1;}}
                '<'=>{if b.get(i+1)==Some(&'='){out.push(Tok::Le);i+=2;}else{out.push(Tok::Lt);i+=1;}}
                '='=>{out.push(Tok::Eq);i+=2;}
                _=>{let mut j=i;while j<b.len()&&!matches!(b[j],'('|')'|'&'|'|'|'>'|'<'|'='|'!'){j+=1;}
                    let word:String=b[i..j].iter().collect::<String>().trim().to_owned();i=j;
                    // numeric literal "f10", "f-6", "f0.01" (the disassembler prints float literals with an f prefix)
                    if let Some(rest)=word.strip_prefix('f'){if let Ok(v)=rest.parse::<f32>(){out.push(Tok::Num(v));continue;}}
                    out.push(Tok::Ident(word));}}
        }out
    }
    struct Eval<'a>{t:Vec<Tok>,p:usize,v:&'a Vars}
    impl<'a> Eval<'a>{
        fn peek(&self)->Option<&Tok>{self.t.get(self.p)}
        fn or(&mut self)->Option<f32>{let mut l=self.and()?;while matches!(self.peek(),Some(Tok::Or)){self.p+=1;let r=self.and()?;l=((l!=0.)||(r!=0.)) as u8 as f32;}Some(l)}
        fn and(&mut self)->Option<f32>{let mut l=self.cmp()?;while matches!(self.peek(),Some(Tok::And)){self.p+=1;let r=self.cmp()?;l=((l!=0.)&&(r!=0.)) as u8 as f32;}Some(l)}
        fn cmp(&mut self)->Option<f32>{let l=self.unary()?;
            let op=match self.peek(){Some(Tok::Gt)=>1,Some(Tok::Ge)=>2,Some(Tok::Lt)=>3,Some(Tok::Le)=>4,Some(Tok::Eq)=>5,_=>return Some(l)};self.p+=1;let r=self.unary()?;
            Some(match op{1=>l>r,2=>l>=r,3=>l<r,4=>l<=r,_=>l==r} as u8 as f32)}
        fn unary(&mut self)->Option<f32>{if matches!(self.peek(),Some(Tok::Not)){self.p+=1;let v=self.unary()?;return Some((v==0.) as u8 as f32);}self.atom()}
        fn atom(&mut self)->Option<f32>{
            match self.t.get(self.p).cloned()?{
                Tok::LP=>{self.p+=1;let v=self.or()?;if !matches!(self.peek(),Some(Tok::RP)){return None;}self.p+=1;Some(v)}
                Tok::Num(n)=>{self.p+=1;Some(n)}
                Tok::Ident(name)=>{self.p+=1;
                    if name=="Abs"&&matches!(self.peek(),Some(Tok::LP)){self.p+=1;let v=self.or()?;self.p+=1;return Some(v.abs());}
                    self.v.lookup(&name)}
                _=>None}}
    }
    fn eval_rule(text:&str,v:&Vars)->Option<bool>{let mut e=Eval{t:tokenize(text),p:0,v};let r=e.or()?;if e.p!=e.t.len(){return None;}Some(r!=0.)}
