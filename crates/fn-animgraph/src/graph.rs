        // LeftArmMaskBlendWeight (bytecode 0x7bee..0x7c31, see LAYERED.md): FInterpTo(cur, (WeaponCoreAnim in {5,13,15} || (WeaponCoreAnim==1 && bIsRelaxedLevel2 && !bIsTargeting)) ? 1 : 0, dt, 10).
        // Enum values 1 / 5 / 13 / 15 = Pistol / MeleeOneHand / TrapPlacement / AbilityDecoTool (declaration order of the EFortWeaponCoreAnimation name table in the 1.8 exe).
