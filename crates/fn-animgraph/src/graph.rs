    /// `FortAnimInstance` native relaxed update (exe 0x40efb0, called from 0x40e100 before BlueprintUpdateAnimation), ported instruction by instruction:
    /// a weapon that has not fired since the last tick and is neither reloading nor charging accumulates `RelaxedLevelTimeCounter += dt` (while equipping the counter is pinned
    /// to `TimeToReachRelaxedLevel1`); anything else stores `SavedWeaponLastFireTime = LastFireTime` and zeroes the counter. Then
    /// `bRecentlyFired = (TimeSeconds - Saved) <= TimeForRecentlyFired`, `bIsRelaxedLevel1 = counter >= TimeToReachRelaxedLevel1`, `bIsRelaxedLevel2 = counter >= TimeToReachRelaxedLevel2`.
    pub fn update_relaxed(&mut self,w:&WeaponClock,dt:f32){
        if w.last_fire_time==self.saved_weapon_last_fire_time&&!w.reloading&&!w.charging{
            if w.equipping{self.relaxed_level_time_counter=TIME_TO_REACH_RELAXED_LEVEL1;}else{self.relaxed_level_time_counter+=dt;}
        }else{self.saved_weapon_last_fire_time=w.last_fire_time;self.relaxed_level_time_counter=0.;}
        self.b_recently_fired=!(w.world_time-self.saved_weapon_last_fire_time>TIME_FOR_RECENTLY_FIRED);
        self.b_is_relaxed_level1=self.relaxed_level_time_counter>=TIME_TO_REACH_RELAXED_LEVEL1;
        self.b_is_relaxed_level2=self.relaxed_level_time_counter>=TIME_TO_REACH_RELAXED_LEVEL2;
    }
