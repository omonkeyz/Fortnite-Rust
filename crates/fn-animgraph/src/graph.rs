// ---- AdditiveJumps
#[derive(Clone,Copy,Debug,PartialEq,Eq)]pub enum JumpState{Idle,Jump,Loop,Fall,Land}
/// What the renderer needs: the current and (while cross-fading) previous source, and the mix between them.
#[derive(Clone,Copy,Debug)]pub struct JumpPose{pub cur:(JumpState,f32),pub prev:Option<(JumpState,f32)>,pub mix:f32}
/// Per-frame inputs of the AdditiveJumps rules (a view of [`Vars`]).
#[derive(Clone,Copy,Debug,Default)]pub struct JumpInput{pub rising:bool,pub falling:bool,pub landing_predicted:bool,pub predicted_time_left:f32,pub crouching:bool}
impl JumpInput{
    pub fn from_vars(v:&Vars)->Self{Self{rising:v.b_is_jumping,falling:v.b_is_falling,landing_predicted:v.b_landing_predicted,predicted_time_left:v.predicted_fall_time_left,crouching:v.is_crouching}}
    /// Same derivation as `Vars::update` from the movement component's state: airborne + vertical speed (m/s) + time to touchdown.
    pub fn from_controller(airborne:bool,vertical_speed:f32,time_left:f32,crouching:bool)->Self{
        let rising=airborne&&vertical_speed>=0.;let falling=airborne&&!rising; // exe 0x40e8a0: bIsJumping = IsFalling && VelZ >= 0
        Self{rising,falling,landing_predicted:falling&&time_left<=FALL_LOOKAHEAD_SECONDS,predicted_time_left:if falling{time_left}else{0.},crouching}
    }
}
/// The AdditiveJumps state machine. States keep their own clocks; transitions follow the baked priority order, at most three per tick
/// (`MaxTransitionsPerFrame`). The machine reads ONLY the movement component's airborne / vertical-speed state (via [`JumpInput`]), never
/// the jump key, so a key press in the air or during landing cannot restart anything.
#[derive(Clone,Debug)]pub struct JumpMachine{pub state:JumpState,pub time:f32,prev:Option<(JumpState,f32)>,mix:f32,tr:Tr,tr_elapsed:f32,pub fall_play_time:f32,pub fall_rate:f32,jump_len:f32,land_len:f32,
    /// Every state change as (tick, from, to): the "state log" the air-jump tests assert on.
    pub log:Vec<(u64,JumpState,JumpState)>,ticks:u64}
impl JumpMachine{
    pub fn new(jump_len:f32,land_len:f32)->Self{Self{state:JumpState::Idle,time:0.,prev:None,mix:1.,tr:tr(0.,Ease::Linear),tr_elapsed:0.,fall_play_time:0.,fall_rate:1.,jump_len,land_len,log:vec![],ticks:0}}
    pub fn default_for_melee()->Self{Self::new(clip_meta("M_JumpUp_ARDS_Additive").map_or(0.4,|c|c.length),clip_meta("M_JumpLand_ARDS_Additive").map_or(0.6,|c|c.length))}
    fn rate(&self,s:JumpState)->f32{match s{JumpState::Fall=>self.fall_rate,JumpState::Loop=>APEX_PLAY_RATE,_=>1.}}
    fn go(&mut self,to:JumpState,t:Tr){self.log.push((self.ticks,self.state,to));self.prev=Some((self.state,self.time));self.state=to;self.time=0.;self.mix=0.;self.tr=t;self.tr_elapsed=0.;}
    /// FallPlayRate bytecode: `FMin(FMax(0.4 - FallAnimPlayTime, 0) / FMax(PredictedFallTimeLeft, 0.01), 1.2)` while a landing is
    /// predicted (FallAnimPlayTime += dt * rate), else rate 1 and the accumulator resets.
    pub fn update_fall_rate(&mut self,i:&JumpInput,dt:f32){
        if i.landing_predicted{self.fall_rate=((FALL_CLIP_SECONDS-self.fall_play_time).max(0.)/i.predicted_time_left.max(0.01)).min(FALL_RATE_MAX);self.fall_play_time+=dt*self.fall_rate;}
        else{self.fall_rate=1.;self.fall_play_time=0.;}
    }
    /// The Jump -> Fall rule (also Loop -> Fall): !bIsJumping && (bLandingPredicted || !bIsFalling).
    fn leave_for_fall(i:&JumpInput)->bool{!i.rising&&(i.landing_predicted||!i.falling)}
    pub fn step(&mut self,i:&JumpInput,dt:f32){
        let dt=dt.max(0.);self.ticks+=1;
        self.update_fall_rate(i,dt);
        self.time+=dt*self.rate(self.state);
        if let Some((s,t))=self.prev{self.prev=Some((s,t+dt*self.rate(s)));self.tr_elapsed+=dt;
            let a=if self.tr.dur<=1e-6{1.}else{(self.tr_elapsed/self.tr.dur).min(1.)};self.mix=ease(self.tr.ease,a);if a>=1.{self.prev=None;self.mix=1.;}}
        // transitions in the baked priority order of each state (report: AdditiveJumps)
        for _ in 0..3{
            let before=self.state;
            match self.state{
                JumpState::Idle=>{if i.falling{self.go(JumpState::Fall,FALL_FROM_IDLE);}else if i.rising&&!i.crouching{self.go(JumpState::Jump,JUMP_FROM_IDLE);}}
                JumpState::Jump=>{if Self::leave_for_fall(i){self.go(JumpState::Fall,TO_FALL);}else if self.time>=self.jump_len-JUMP_TO_LOOP.dur{self.go(JumpState::Loop,JUMP_TO_LOOP);}}
                JumpState::Loop=>{if Self::leave_for_fall(i){self.go(JumpState::Fall,TO_FALL);}}
                JumpState::Fall=>{if !i.falling{self.go(JumpState::Land,FALL_TO_LAND);}}
                JumpState::Land=>{if self.time>=self.land_len-LAND_TO_IDLE_AUTO.dur{self.go(JumpState::Idle,LAND_TO_IDLE_AUTO);}else if i.rising||i.falling{self.go(JumpState::Idle,LAND_TO_IDLE_INTERRUPT);}}
            }
            if self.state==before{break;}
        }
    }
    /// Length of the Land state's relevant (highest weight) sequence player: the ARDS land (0.6 s) or, while JumpLandStarted selects pin 0, the NoWep Core land.
    pub fn set_land_len(&mut self,len:f32){self.land_len=len;}
    pub fn pose(&self)->JumpPose{JumpPose{cur:(self.state,self.time),prev:self.prev,mix:self.mix}}
    /// `GetStateWeight(AdditiveJumps, state)`: the cross-fade weight of one state (current: mix, previous: 1 - mix).
    pub fn state_weight(&self,s:JumpState)->f32{
        let mut w=0.;if self.state==s{w+=if self.prev.is_some(){self.mix}else{1.};}
        if let Some((p,_))=self.prev{if p==s{w+=1.-self.mix;}}
        w
    }
    /// State sequence with consecutive duplicates removed (starting from Idle).
    pub fn visited(&self)->Vec<JumpState>{let mut v=vec![JumpState::Idle];for (_,_,to) in &self.log{if v.last()!=Some(to){v.push(*to);}}v}
}

