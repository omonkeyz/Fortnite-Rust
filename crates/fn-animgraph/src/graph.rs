fn sequence_length(name:&str)->f32{clip_meta(name).map_or(1.,|c|c.length/(c.rate_scale.max(1e-6)))}
/// Grid weights of `def` at `input` (clamped to the axes): the bilinear blend of the four surrounding grid elements, each of which carries
/// up to three baked sample weights (the serialized triangulation). Returns (sample index, weight) pairs, normalised to 1.
pub fn grid_weights(def:&BsDef,input:[f32;2])->Vec<(usize,f32)>{
    let one_d=def.class=="BlendSpace1D";
    let (gx,gy)=(def.axes[0].grid as usize,if one_d{0}else{def.axes[1].grid as usize});
    let norm=|a:&Axis,v:f32|{let r=a.max-a.min;if r.abs()<1e-9{0.}else{((v.clamp(a.min,a.max)-a.min)/r).clamp(0.,1.)}};
    let (nx,ny)=(norm(&def.axes[0],input[0]),if one_d{0.}else{norm(&def.axes[1],input[1])});
    let (fx,fy)=(nx*gx as f32,ny*gy as f32);
    let (ix,iy)=((fx.floor() as usize).min(gx.saturating_sub(1)),if gy==0{0}else{(fy.floor() as usize).min(gy-1)});
    let (rx,ry)=(if gx==0{0.}else{fx-ix as f32},if gy==0{0.}else{fy-iy as f32});
    let at=|x:usize,y:usize|def.grid.get(x*(gy+1)+y);
    let corners:[(usize,usize,f32);4]=[(ix,iy,(1.-rx)*(1.-ry)),(ix+1,iy,rx*(1.-ry)),(ix,iy+1,(1.-rx)*ry),(ix+1,iy+1,rx*ry)];
    let mut out:Vec<(usize,f32)>=vec![];
    for (x,y,wc) in corners{
        if wc<=0.{continue;}
        let Some(e)=at(x.min(gx),y.min(gy))else{continue};
        for k in 0..3{if e.idx[k]>=0&&(e.idx[k] as usize)<def.samples.len()&&e.w[k]>0.{let i=e.idx[k] as usize;let w=e.w[k]*wc;match out.iter_mut().find(|(j,_)|*j==i){Some(o)=>o.1+=w,None=>out.push((i,w))}}}
    }
    let sum:f32=out.iter().map(|o|o.1).sum();if sum>1e-9{for o in &mut out{o.1/=sum;}}
    out
}
/// `AnimNode_BlendSpacePlayer` state: smoothed sample weights, sync time and the leader sample.
#[derive(Clone,Debug)]pub struct BlendSpace{pub def:&'static BsDef,weights:Vec<f32>,filt:[f32;2],filt_init:bool,norm_time:f32,times:Vec<f32>,primed:bool}
impl BlendSpace{
    pub fn new(def:&'static BsDef,start_position:f32)->Self{let n=def.samples.len();Self{def,weights:vec![0.;n],filt:[0.;2],filt_init:false,norm_time:start_position.clamp(0.,1.),times:vec![0.;n],primed:false}}
    /// Back to the freshly initialised state (a state machine re-entering the state, `InternalTimeAccumulator = StartPosition`).
    pub fn reset(&mut self,start_position:f32){*self=Self::new(self.def,start_position);}
    pub fn active_times(&self)->Vec<(&'static str,f32)>{let mut v:Vec<(&'static str,f32)>=vec![];for i in 0..self.weights.len(){if self.weights[i]>1e-5{let a=self.def.samples[i].anim;if !v.iter().any(|x|x.0==a){v.push((a,self.times[i]));}}}v}
    /// Axis input after the clamp and the per-axis filter. `BSIT_Average` with time 0 passes the value through; with a time it is a
    /// first-order smoothing over that time (APPROXIMATION: UE's FFilterInterpolator for Cubic / EaseInOut shapes the step differently).
    fn filter(&mut self,input:[f32;2],dt:f32)->[f32;2]{
        let c=[input[0].clamp(self.def.axes[0].min,self.def.axes[0].max),input[1].clamp(self.def.axes[1].min,self.def.axes[1].max)];
        if !self.filt_init{self.filt=c;self.filt_init=true;return c;}
        for a in 0..2{let t=self.def.axes[a].interp_time;self.filt[a]=if t<=1e-6{c[a]}else{self.filt[a]+(c[a]-self.filt[a])*(1.-(-dt/t*3.).exp())};}
        self.filt
    }
    /// One tick: filter the input, interpolate the sample weights (`TargetWeightInterpolationSpeedPerSec`, FInterpTo) and advance the sync
    /// time (marker sync with the highest-weighted marker sample as leader when `SampleIndexWithMarkers >= 0`, else normalised time).
    pub fn update(&mut self,input:[f32;2],play_rate:f32,dt:f32){
        let f=self.filter(input,dt);let target=grid_weights(self.def,f);
        let mut tw=vec![0.;self.weights.len()];for (i,w) in target{tw[i]=w;}
        let speed=self.def.target_weight_speed;
        if !self.primed||speed<=0.{self.weights=tw;self.primed=true;}
        else{for i in 0..self.weights.len(){self.weights[i]=finterp_to(self.weights[i],tw[i],dt,speed);}let s:f32=self.weights.iter().sum();if s>1e-6{for w in &mut self.weights{*w/=s;}}}
        let active:Vec<usize>=(0..self.weights.len()).filter(|i|self.weights[*i]>1e-4).collect();
        if active.is_empty(){return;}
        let use_markers=self.def.sample_index_with_markers>=0&&active.iter().any(|i|clip_meta(self.def.samples[*i].anim).map_or(false,|c|c.markers.len()>=2));
        let rate=play_rate.max(0.);
        if use_markers{
            // leader = highest weight sample that has markers; it advances at its own rate, followers sit at the same marker phase
            let leader=*active.iter().filter(|i|clip_meta(self.def.samples[**i].anim).map_or(false,|c|c.markers.len()>=2)).max_by(|a,b|self.weights[**a].partial_cmp(&self.weights[**b]).unwrap_or(std::cmp::Ordering::Equal)).unwrap();
            let lname=self.def.samples[leader].anim;let llen=sequence_length(lname);
            let sample_rate=self.def.samples[leader].rate.max(1e-6);
            let lt=(self.times[leader]+dt*rate*sample_rate).rem_euclid(llen.max(1e-6));
            self.times[leader]=lt;
            let lmeta=clip_meta(lname).unwrap();let phase=marker_phase(lmeta.markers,llen,lt);
            for &i in &active{if i==leader{continue;}
                let n=self.def.samples[i].anim;let len=sequence_length(n);
                self.times[i]=match (clip_meta(n),phase.as_ref()){(Some(m),Some(ph))=>marker_time(m.markers,len,ph).unwrap_or(lt/llen*len),_=>lt/llen*len};}
            // the same clip at several sample points shares one time
            for &i in &active{let n=self.def.samples[i].anim;if let Some(&j)=active.iter().find(|j|self.def.samples[**j].anim==n){self.times[i]=self.times[j];}}
        }else{
            let mut len=0.;let mut wsum=0.;for &i in &active{len+=sequence_length(self.def.samples[i].anim)/self.def.samples[i].rate.max(1e-6)*self.weights[i];wsum+=self.weights[i];}
            if wsum>0.{len/=wsum;}
            self.norm_time=(self.norm_time+dt*rate/len.max(1e-6)).rem_euclid(1.);
            for &i in &active{self.times[i]=self.norm_time*sequence_length(self.def.samples[i].anim);}
        }
    }
    /// `AxisToScaleAnimation` (BSA_Y on every speed-matched locomotion space): the animation is scaled by (input speed) / (the animation's own
    /// value on that axis). The exported sample positions cannot be that value (the same clip sits on the Y = 237 and Y = 385 rows of the jog space,
    /// 149 / 150 on the walk space, 150 / 151 on the crouch spaces), so the "animation axis value" is each clip's measured planted-sole travel speed
    /// (`stride_cm_s`, cm/s at play rate 1). Returns the weight-blended value for the current sample weights, None until the weights exist or when a
    /// weighted clip has no measurement.
    pub fn animation_axis_value(&self)->Option<f32>{
        let (mut sum,mut wsum)=(0.,0.);
        for (i,s) in self.def.samples.iter().enumerate(){let w=self.weights[i];if w>1e-4{sum+=w*stride_cm_s(s.anim)?;wsum+=w;}}
        if wsum>1e-4{Some(sum/wsum)}else{None}
    }
    /// (sample index, weight, clip time) of every sample with weight.
    pub fn contributions(&self)->Vec<(usize,f32,f32)>{(0..self.weights.len()).filter(|i|self.weights[*i]>1e-4).map(|i|(i,self.weights[i],self.times[i])).collect()}
    /// The pose node: samples of the same clip merged (they share one time).
    pub fn node(&self,looping:bool)->Node{
        let mut v:Vec<(Node,f32)>=vec![];
        for (i,w,t) in self.contributions(){let n=self.def.samples[i].anim;
            match v.iter_mut().find(|(c,_)|matches!(c,Node::Clip{name,..} if name==n)){Some(x)=>x.1+=w,None=>v.push((Node::Clip{name:n.to_owned(),time:t,looping},w))}}
        if v.is_empty(){return Node::Ref;}
        Node::Mix(v)
    }
    /// Pure evaluation at an input: (sample, weight, clip time) with every sample at the normalised `phase` (marker-synced spaces: the
    /// highest-weighted marker sample is the leader at `phase`, followers sit at the same marker phase). No smoothing, no clocks.
    pub fn sample_weights(def:&'static BsDef,input:[f32;2],phase:f32)->Vec<(usize,f32,f32)>{
        let w=grid_weights(def,input);
        let has_markers=|i:usize|clip_meta(def.samples[i].anim).map_or(false,|c|c.markers.len()>=2);
        if def.sample_index_with_markers>=0&&w.iter().any(|o|has_markers(o.0)){
            let leader=w.iter().filter(|o|has_markers(o.0)).max_by(|a,b|a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal)).unwrap().0;
            let lname=def.samples[leader].anim;let llen=sequence_length(lname);let lt=(phase*llen).rem_euclid(llen.max(1e-6));
            let ph=marker_phase(clip_meta(lname).unwrap().markers,llen,lt);
            return w.iter().map(|&(i,wt)|{let n=def.samples[i].anim;let len=sequence_length(n);
                let t=if i==leader||n==lname{lt}else{match (clip_meta(n),ph.as_ref()){(Some(m),Some(p))=>marker_time(m.markers,len,p).unwrap_or(lt/llen*len),_=>lt/llen*len}};(i,wt,t)}).collect();
        }
        w.iter().map(|&(i,wt)|(i,wt,phase*sequence_length(def.samples[i].anim))).collect()
    }
    pub fn sample_node(def:&'static BsDef,input:[f32;2],phase:f32)->Node{
        let mut v:Vec<(Node,f32)>=vec![];
        for (i,wt,t) in Self::sample_weights(def,input,phase){let n=def.samples[i].anim;match v.iter_mut().find(|(c,_)|matches!(c,Node::Clip{name,..} if name==n)){Some(x)=>x.1+=wt,None=>v.push((Node::Clip{name:n.to_owned(),time:t,looping:true},wt))}}
        Node::Mix(v)
    }
    pub fn weight_of(&self,anim:&str)->f32{(0..self.weights.len()).filter(|i|self.def.samples[*i].anim==anim).map(|i|self.weights[i]).sum()}
}
/// Marker phase of a time inside a looping clip: (previous marker name, next marker name, fraction between them).
fn marker_phase(markers:&[(&str,f32)],len:f32,t:f32)->Option<(String,String,f32)>{
    if markers.len()<2{return None;}
    let mut sorted:Vec<(&str,f32)>=markers.to_vec();sorted.sort_by(|a,b|a.1.partial_cmp(&b.1).unwrap_or(std::cmp::Ordering::Equal));
    let n=sorted.len();
    for k in 0..n{let (a,ta)=sorted[k];let (b,tb)=sorted[(k+1)%n];let tb=if k+1==n{tb+len}else{tb};let tt=if t<sorted[0].1&&k+1==n{t+len}else{t};
        if tt>=ta&&tt<tb{return Some((a.to_owned(),b.to_owned(),(tt-ta)/(tb-ta).max(1e-6)));}}
    None
}
/// Time in a looping clip at `fraction` between its markers `prev` and `next` (None when the clip lacks one of them).
fn marker_time(markers:&[(&str,f32)],len:f32,phase:&(String,String,f32))->Option<f32>{
    let ta=markers.iter().find(|m|m.0==phase.0)?.1;let mut tb=markers.iter().find(|m|m.0==phase.1)?.1;
    if tb<=ta{tb+=len;}
    Some((ta+(tb-ta)*phase.2).rem_euclid(len.max(1e-6)))
}

