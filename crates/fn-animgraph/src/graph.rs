/// A timed 0..1 cross-fade with UE semantics: a new target restarts the ramp from the current value.
#[derive(Clone,Copy,Debug)]pub struct Blend{pub value:f32,start:f32,target:f32,elapsed:f32,tr:Tr}
impl Blend{
    pub fn new(value:f32)->Self{Self{value,start:value,target:value,elapsed:0.,tr:tr(0.,Ease::Linear)}}
    pub fn target(&self)->f32{self.target}
    /// Retarget; no effect while already heading to `target`.
    pub fn go(&mut self,target:f32,t:Tr){if (target-self.target).abs()>1e-6{self.start=self.value;self.target=target;self.elapsed=0.;self.tr=t;}}
    pub fn step(&mut self,dt:f32){self.elapsed+=dt.max(0.);let a=if self.tr.dur<=1e-6{1.}else{(self.elapsed/self.tr.dur).min(1.)};self.value=self.start+(self.target-self.start)*ease(self.tr.ease,a);}
}

/// `AnimNode_BlendListByBool/Enum` cross-fade: every child has its own alpha blend; switching the active child restarts all of them from
/// their current value (target 1 for the new child, 0 otherwise) over `BlendTime[new child]`; the weights are normalised.
#[derive(Clone,Debug)]pub struct BlendList{w:Vec<f32>,start:Vec<f32>,target:Vec<f32>,elapsed:f32,time:f32,ease:Ease,active:usize}
impl BlendList{
    pub fn new(n:usize,active:usize,ease:Ease)->Self{let mut w=vec![0.;n];w[active]=1.;Self{start:w.clone(),target:w.clone(),w,elapsed:0.,time:0.,ease,active}}
    /// Selects the active child (a change retargets the cross-fade) and advances time.
    pub fn step(&mut self,active:usize,blend_time:f32,dt:f32){
        if active!=self.active{self.active=active;self.start=self.w.clone();for (i,t) in self.target.iter_mut().enumerate(){*t=if i==active{1.}else{0.};}self.elapsed=0.;self.time=blend_time;}
        self.elapsed+=dt.max(0.);let a=if self.time<=1e-6{1.}else{(self.elapsed/self.time).min(1.)};let e=ease(self.ease,a);
        for i in 0..self.w.len(){self.w[i]=self.start[i]+(self.target[i]-self.start[i])*e;}
        let sum:f32=self.w.iter().sum();if sum>1e-6{for x in &mut self.w{*x/=sum;}}
    }
    pub fn weights(&self)->&[f32]{&self.w}
    pub fn active(&self)->usize{self.active}
}

