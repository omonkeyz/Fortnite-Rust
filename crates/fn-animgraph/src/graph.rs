/// One node of the pose tree the AnimGraph describes. Evaluated bottom-up by `Skeleton::eval_pose`. Clips are referenced by name.
#[derive(Clone,Debug)]pub enum Node{
    /// Reference pose (identity in an additive context).
    Ref,
    Clip{name:String,time:f32,looping:bool},
    /// Normalised weighted blend of poses (lerp / shortest-arc nlerp).
    Mix(Vec<(Node,f32)>),
    /// Two-state cross-fade with a transition BlendProfile: bone weight = clamp(w * scale(bone)) (scale 1 for unlisted bones).
    MixProfile{from:Box<Node>,to:Box<Node>,w:f32,profile:&'static [(&'static str,f32)]},
    ApplyAdditive{base:Box<Node>,add:Box<Node>,alpha:f32},
    /// AAT_RotationOffsetMeshSpace additive (AnimNode_ApplyMeshSpaceAdditive).
    ApplyMeshAdditive{base:Box<Node>,add:Box<Node>,alpha:f32},
    /// AnimNode_LayeredBoneBlend with one blend pose; `filters` = (bone, BlendDepth) branch filters.
    Layered{base:Box<Node>,blend:Box<Node>,filters:Vec<(&'static str,i32)>,weight:f32,mesh_space:bool,curve_blend:CurveBlend},
    /// AnimNode_RotateRootBone: yaw / pitch (degrees, UE sign: yaw + = right, pitch + = up) applied to the root bone in component space.
    RotateRoot{base:Box<Node>,yaw:f32,pitch:f32},
    /// AnimNode_RotationOffsetBlendSpace: additive aim offset (mesh-space rotation offsets) blended by `samples` (clip, weight).
    AimOffset{base:Box<Node>,samples:Vec<(String,f32)>,alpha:f32},
    TwoBoneIk{base:Box<Node>,ik:TwoBone,alpha:f32},
    HandRetarget{base:Box<Node>,fk_weight:f32,alpha:f32},
    /// `AnimNode_CopyBone` in component space.  `alpha` is the blended
    /// `SnapWeapon_LHand` float curve (ubergraph 0x6619).
    CopyBone{base:Box<Node>,from:&'static str,to:&'static str,alpha:f32},
    /// AnimNode_ModifyBone, rotation mode Additive in component space (UE yaw + = right, pitch + = up); identity when both are 0.
    ModifyBone{base:Box<Node>,bone:&'static str,yaw:f32,pitch:f32},
    /// ModifyBone (head) driven by the native HeadTrackingReticleAdjustment: rotates the head so its forward axis points `yaw` / `pitch`
    /// (degrees, UE sign, relative to the visible body) with each angle limited to `limit`. 0 in 1.8 (bAimWeaponTowardsReticle is off), so the node is a no-op.
    HeadTrack{base:Box<Node>,yaw:f32,pitch:f32,limit:f32},
}
